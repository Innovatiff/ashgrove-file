#!/usr/bin/env node
// Turns the chosen venue photographs into the WebP files the main website
// ships, each in a few widths so a phone is not sent a desktop's picture.
//
//   node scripts/process-venue.mjs                  process everything
//   node scripts/process-venue.mjs --only desk      process one or more (comma separated)
//
// Sources are read from .image-src/venue/{name}.png (git-ignored: they are
// about 10 MB each). How they were made is in docs/image-prompts.md.
//
// Output
//   public/venue/{name}-{width}.webp      one file per width
//   lib/site/venue.generated.ts           dimensions and sources, read by <Photo>
//
// These are the main website's pictures. A room's own pictures are made by
// scripts/process-images.mjs and live under /public/images.

import { existsSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(root, '.image-src', 'venue');
const outDir = path.join(root, 'public', 'venue');
const args = process.argv.slice(2);
const only = args.includes('--only') ? args[args.indexOf('--only') + 1]?.split(',').map((name) => name.trim()) : undefined;

// The widest file of each is the one a large, sharp screen gets. The others
// are for smaller ones. Widths are what the picture is shown at, doubled.
//
// A picture may also be a part of another one: `from` names the source it is
// cut from, and `crop` says which part, in pixels of that source.
export const PHOTOS = [
  { name: 'reception', widths: [960, 1600, 2400] },
  { name: 'desk', widths: [800, 1400, 2000] },
  { name: 'notices', widths: [640, 960, 1280] },
  { name: 'lockers', widths: [640, 960, 1280] },
  { name: 'corridor', widths: [960, 1600, 2400] },
  { name: 'keys', widths: [800, 1200, 1600] },
  // The first hook of the key rack, close: the key that can be taken.
  { name: 'key', from: 'keys', crop: { left: 124, top: 330, width: 1958, height: 1700 }, widths: [560, 1000] },
  { name: 'door', widths: [640, 960, 1280] },
];

await mkdir(outDir, { recursive: true });
const manifest = {};
let failed = 0;

for (const photo of PHOTOS) {
  const src = path.join(srcDir, `${photo.from ?? photo.name}.png`);
  const skip = only && !only.includes(photo.name);
  const sources = [];

  for (const width of photo.widths) {
    const out = path.join(outDir, `${photo.name}-${width}.webp`);
    if (!skip) {
      if (!existsSync(src)) {
        console.error(`MISSING  ${photo.name}: no source at ${path.relative(root, src)}`);
        failed++;
        break;
      }
      const picture = photo.crop ? sharp(src).extract(photo.crop) : sharp(src);
      await picture
        .resize({ width, kernel: 'lanczos3', withoutEnlargement: true })
        .webp({ quality: 80, effort: 6, smartSubsample: true })
        .toFile(out);
    }
    if (!existsSync(out)) continue;
    const meta = await sharp(out).metadata();
    const kb = Math.round((await sharp(out).toBuffer()).length / 1024);
    sources.push({ src: `/venue/${photo.name}-${width}.webp`, width: meta.width, height: meta.height, kb });
  }

  if (sources.length === 0) continue;
  const largest = sources[sources.length - 1];
  manifest[photo.name] = { width: largest.width, height: largest.height, sources };
  console.log(
    `${skip ? 'kept    ' : 'wrote   '} ${photo.name.padEnd(10)} ${String(largest.width).padStart(4)}x${String(largest.height).padEnd(4)}  ` +
      sources.map((source) => `${source.width}w ${source.kb} KB`).join('   '),
  );
}

const ts =
  `// Generated by scripts/process-venue.mjs. Do not edit.\n` +
  `// The main website's photographs: their size, and the same picture at each width.\n\n` +
  `export const venuePhotos = {\n` +
  Object.entries(manifest)
    .map(
      ([name, photo]) =>
        `  ${name}: {\n    width: ${photo.width},\n    height: ${photo.height},\n    sources: [\n` +
        photo.sources.map((source) => `      { src: '${source.src}', width: ${source.width} },`).join('\n') +
        `\n    ],\n  },`,
    )
    .join('\n') +
  `\n} as const;\n\nexport type VenuePhotoName = keyof typeof venuePhotos;\n`;
await mkdir(path.join(root, 'lib', 'site'), { recursive: true });
await writeFile(path.join(root, 'lib', 'site', 'venue.generated.ts'), ts);

if (failed > 0) {
  console.error(`\n${failed} photograph(s) have no source.`);
  process.exit(1);
}
